# Logical operators. There are 3 types - and, or not

# and operator - Returns False if atleast one value is False, 
# Returns True only if both values are True

# print(True and False) # False
# print(False and True) # False
# print(True and True) # True
# print(False and False)# False

# or operator - Returns True even if one value is True, returns False if both values are False

print(True or False) #True
print(False or True) # True
print(True or True) # True
print(False or False) # False

