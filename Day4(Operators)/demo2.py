# Increment assign - Adds the number given to the value and reassigns to the same variable.
# Here 10 (initial a value) is getting added to 2 and reassigned to a giving 12 as result
a = 10
# a = a + 2
# a = 10 + 2
print('before increment a value',a)
# before increment a value 10
a += 2
print('after increment a value',a)
# after increment a value 12


b = 20
b += 4
print(b)
# 24

# Decrement assign - Subtracts the value and reassigns to the same variable
x = 40
x -= 10
# Working
# x = x -10
print(x)
# 30

y = -20
y -= 4
print(y)
# -24


