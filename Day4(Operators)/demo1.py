# Operators
# Python has inbuilt operators for performing specific operations on operands. 
# Ex : res = var1 + var2
# var1 is operand1
# var2 is operand2
# + is an operator


# There are 7 operators
# 1. Arithmetic operators
# 2. Assignment operators
# 3. Logical operators
# 4. Comparison operators (Relational operators)
# 5. Membership operators
# 6. Identity operators
# 7. Bitwise operators

# Arithmetic operators - Addition (+), Subtraction(-), Multiplication(*), Division(/), 
# Floor Division(//), Modulus(%), Exponentiation(**)

# Addition (+) - Adds 2 or more variables and gives us the result

var1 = 10
var2 = 20
res = var1 + var2
print('Addition',res)
# Addition 30

# Subtraction (-) 
var1 = -30
var2 = 5
res1 = var1 - var2
print('Subtraction',res1)
# Subtraction -35

# Multiplication (*)
m1 = 12
m2 = 5
res2 = m1*m2
print('Multiplication',res2)
# Multiplication 60


# Division(/)- Divides 2 numbers and gives us the quotient in float
d1 = 50
d2 = 10
print('Division',d1/d2)
# Division 5.0

# Floor Division (//). It divides and discards the decimal part and gives us the integer 
# value (whole number)
f1 = 9
f2 = 2
res3 = f1//f2
print('Floor Division',res3)
# Floor Division 4

f3 = 4.5
f4 = 5.0
print(f3//f4)
# 0.0

# Modulus (%) - Divides and gives us the remainder
mod1 = 10
mod2 = 5
res4 = mod1%mod2
print('Modulus',res4)
# Modulus 0

mod3 = 7
mod4 = 3
res5 = mod3%mod4
print(res5)
# 1

# Exponentiation (**) - Power of a number, Ex : e1 to the power of e3 which is 4 to the power of 3
e1 = 4
e2 = 3
res6 = e1**e2
print('Exponentiation',res6)
# Exponentiation 64

print(5**2)
# 25


