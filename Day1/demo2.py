# Different ways of creating and assigning variables
# 1. Single value assigned to a single variable

a = 20

# 2. Single value assigned to multiple variables
x=y=z=30
# print(x)
# print(y)
# print(z)

# 3. Multiple values assigned to multiple variables in a single line with semicolon
a=10; b=40; c=50
print(a)
print(b)
print(c)
# 10
# 40
# 50

# without using semicolon
(l,m,n) = (11,22,33)
print("l value is:",l)
print("m value is:",m)
print('n value is:',n)

# l value is: 11
# m value is: 22
# n value is: 33
