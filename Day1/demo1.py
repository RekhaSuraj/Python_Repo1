# Translators - Which converts High level language to Machine language
# There are 2 types
# 1. Compiler - Reads the entire source code together and if there are no errors, it converts into machine language, 
# else it gives us an error message
# 2. Interpreter - Reads the source code line by line and if there are no errors, it converts into machine langauage,
# else immediately it specifies the error. Faster compared to compiler

