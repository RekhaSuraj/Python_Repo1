# Conversion from decimal to binary, 
# Binary contains only 0s and 1s and it is prefixed with 0b
# Syntax : bin(num) - inbuilt method, converts a decimal number to binary

# Decimal to binary conversion
var1 = 10
var2 = bin(var1)
print(var2)
# 0b1010

a = 500
b = bin(a)
print(b)
# 0b111110100
print(type(b))
# <class 'str'>

print(bin(321))
# 0b101000001

# Binary to decimal conversion
a2 = 0b1001
print(a2)
# 9

