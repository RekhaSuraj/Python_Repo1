# Greater than or equal to (>=) - Returns True if x is greater than or Equal to y, else it returns False

x = 20
y = 10

print(x>=y)
# True

x1 = 40
x2 = 50
print(x1>=x2)
# False

print(20>=20)
# True

# Lesser than or Equal to (<=) - Returns True if x is lesser than or equal to y, else it returns False
print('----------Lesser than or Equal to-------')
x = 50
y = 25
print(x<=y)
# False

x1 = -40
x2 = -10
print(x1<=x2)
# True






