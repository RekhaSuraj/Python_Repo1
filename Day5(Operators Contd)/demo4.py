# Membership Operator - Applicable for iterables (String, List, Tuple, Set, Frozen set, dictionary)
# There are 2 types - in, not in

family = ['Vittal','Gopal','Saroja','Uday','Sandhya','Usha']

# in - Returns True if value is present in the iterable, else it returns False
print('Rekha' in family)
# False

print('Vittal' in family)
# True

# not in - Returns True if value is not present in the iterable
print('Sanjay' not in family)
# True


s1 = 'hello'
print('e' in s1)
# True

print('x' in s1)
# False

print('y' not in s1)
# True








