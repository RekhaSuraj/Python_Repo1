# Comparison Operators (Relational operators)
# There are 6 types
# 1. Greater than (>)
# 2. Lesser than (<)
# 3. Greater than or equal to(>=)
# 4. Lesser than or equal to(<=)
# 5. Equal to(==)
# 6. Not Equal to(!=)

# 1. Greater than (>)

a = 20
b = 10
print(a>b)
# True

a1 = -30
a2 = -10
print(a1>a2)
# False

# 2. Lesser than (<)
x = 45
y = -20
print(x<y)
# False

x1 = 3.25
x2 = 0.45
print(x2<x1)
# True







