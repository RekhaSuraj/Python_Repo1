# Equal to (==) - Returns True if x and y have the same value, else Returns False

x = 55
y = 55
print(x==y)
# True

x1 = 30
x2 = 40

print(x1==x2)
# False

s1 = 'hi'
s2 = 'hi'
print(s1==s2)
# True

