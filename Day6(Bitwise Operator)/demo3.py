# Bitwise shiftleft (<<) - This adds bits from right to left (or moves) to the number of positions
# specified

x = 5
print('Bitwise shift left:',x<<1) # Moving 1 bit to the left
# Bitwise shift left: 10

print(x<<2) # Moving 2 bits to the left
# 20


# Bitwise shiftright(>>) - This looses bits from left to right(or moves) to the number of positions
# specified
b1 = 5
print('bitwise shift right:',b1 >> 1)
# bitwise shift right: 2

print(b1>>2)
# 1

