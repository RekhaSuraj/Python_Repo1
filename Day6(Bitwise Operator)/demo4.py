# String - String is a sequence of characters like letters, alphabets, 
# String is immutable (cannot be modified or changed)
# Ex: 'Hello'
# String can be enclosed inside single quotes or double quotes

str1 = 'hello'
print(str1)
# hello

str2 = "hello1"
print(str2)
# hello1

print(type(str1))
# <class 'str'>

# Typecasting or conversion - Conversion from string to int
a1 = '30'
print('before conversion',type(a1))
# before conversion <class 'str'>

b1 = int(a1)
print(b1)
print('after conversion',type(b1))
# after conversion <class 'int'>


