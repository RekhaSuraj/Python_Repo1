# Bitwise operators - There are 6 operators, applicable for binaries
# 1. Bitwise and (&)
# 2. Bitwise or (|)
# 3. Bitwise XOR (^)
# 4. Bitwise not (~)
# 5. Bitwise shiftleft (<<)
# 6. Bitwiese shiftright(>>)


# Bitwise and(&) - Performs and operation on binary value of the given numbers

a = 5
b = 6
print('Bitwise and - ',a & b)
# Bitwise and -  4

x1 = 3
x2 = 8
print(x1 & x2)
# 0

# Bitwise or (|) - Performs or operation on binary value of the given numbers
l = 5
m = 6
print('Bitwise or -',l | m)
# Bitwise or - 7


# Bitwise XOR(^) - Exclusive Or, Returns True only if one value is true, if both values are true, 
# it returns False
s1 = 5
s2 = 6
print('Bitwise XOR - ',s1^s2)
# Bitwise XOR -  3