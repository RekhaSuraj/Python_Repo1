# Boolean Datatype - It has 2 values, True and False.
# True holds value 1, False holds value 0

b1 = True
print('value of b1:',b1)
# value of b1: True

print('type of b1:',type(b1))
# type of b1: <class 'bool'>

b2 = False
print('value of b2:',b2)
# value of b2: False

print('type of b2:',type(b2))
# type of b2: <class 'bool'>

