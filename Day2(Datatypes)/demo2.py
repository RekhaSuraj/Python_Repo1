# Python has inbuilt datatypes
# 1.Numeric - int, float, complex
# 2.Boolean - True and False
# 3.Text datatype - String
# 4.Sequential datatype - list, tuple, set, frozenset, dictionary

# Numeric 
# int - Contains numbers like 1,2,3,4 also negative numbers like -1,-2,-3,-4
var1 = 35
print('value in var1 is:',var1)

print(type(var1))

# type() - Returns the datatype of the object
# Syntax - type(obj)

var2 = -50
print('var2 value is:',var2)
# var2 value is: -50
print('type of var2 is:',type(var2))
# type of var2 is: <class 'int'>




