# String Methods
str1 = 'python Developer'

# print(help(str))

# capitalize - First letter of the string will be capitalized and returned
print(str1.capitalize())
# Python developer

# upper - returns entire string converted to upper case
print(str1.upper())
# PYTHON DEVELOPER

# title() - converts first letter of every word to upper case
print(str1.title())
# Python Developer

# lower() -converts the entire string to lower case
print(str1.lower())
# python developer


