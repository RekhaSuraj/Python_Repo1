# Step index -1 - Reverses the string

str1 = 'Dont worry be happy'

print(str1[::-1])
# yppah eb yrrow tnoD

# +ve slicing
# Fetch 'yrrow' from the above string
print(str1[9:4:-1])
# yrrow

# Fetch 'eb yrrow' from the above string
print(str1[12:4:-1])
# eb yrrow

# -ve slicing
print(str1[-10:-15:-1])
# yrrow

